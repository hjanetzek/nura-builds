#!/bin/sh
# The stage seed of targets/zynthian-testing.sh: writes the recipe aports/zynthian/zynthian-ui-testing from
# zynthian-ui's (same build: the Python tree, the zynlibs and the DrivenByMoss drivers from the
# checkout of zynthian-ui's testing branch; same paths), then seeds the distfiles as for zynthian-ui.
# Generated at each build rather than kept as a copy, so it never lags behind zynthian-ui's recipe:
# only the name, the description and provides="zynthian-ui=..." differ. Like the upstream variants
# (zynthian-ui-tomita), it provides zynthian-ui: apk installs one of them, the kiosk package works
# with either (switch: apk del <the installed one>; apk add <the other>, zynthian-ui's switch_ui.sh).
# The recipe directory is ignored by git (.gitignore).
#
# Usage: zynthian-ui-testing.sh [pmbootstrap config]   (build.sh runs it as SEED_testing;
#        NO_SEED=1: only the recipe)
# (Here and not in aports/zynthian/: a change to it shouldn't trigger zynthian.yml.)
set -eu

here=$(cd "$(dirname "$0")/../aports/zynthian" && pwd)
src=$here/zynthian-ui/APKBUILD
dst=$here/zynthian-ui-testing/APKBUILD
grep -q '^pkgname=zynthian-ui$' "$src" || { echo "$src: no pkgname=zynthian-ui" >&2; exit 1; }
grep -qE '^(provides|replaces|install)=' "$src" &&
	{ echo "$src: has provides/replaces/install now: adapt zynthian-ui-testing.sh" >&2; exit 1; }
mkdir -p "$(dirname "$dst")"
{
	echo "# Generated by scripts/zynthian-ui-testing.sh from zynthian-ui's recipe: built from"
	echo "# zynthian-ui's testing branch (targets/zynthian-testing.sh). Not edited by hand."
	sed -e 's/^pkgname=zynthian-ui$/pkgname=zynthian-ui-testing/' \
		-e 's/^pkgdesc="\(.*\)"$/pkgdesc="\1 (testing branch)"/' "$src" |
		awk '{ print } /^pkgrel=/ { print "provides=\"zynthian-ui=$pkgver-r$pkgrel\"" }'
} > "$dst"
grep -q '^pkgname=zynthian-ui-testing$' "$dst" && grep -q '^provides="zynthian-ui=' "$dst" ||
	{ echo "$dst: generation failed" >&2; exit 1; }
echo "zynthian-ui-testing: recipe generated from zynthian-ui's"

# The distfiles: the same sources as zynthian-ui
[ "${NO_SEED:-}" ] && exit 0
exec "$here/seed-distfiles.sh" "$@"
